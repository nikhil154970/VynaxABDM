async function seedPharmacyMedicines(prisma) {
  let created = 0;
  let skipped = 0;

  for (const med of MEDICINES) {
    const existing = await prisma.pharmacyMedicine.findUnique({
      where: { barcode: med.barcode },
    });
    if (existing) {
      skipped += 1;
      continue;
    }
    await prisma.pharmacyMedicine.create({ data: med });
    created += 1;
  }

  return { created, skipped, total: MEDICINES.length };
}

module.exports = { seedPharmacyMedicines, MEDICINES };
