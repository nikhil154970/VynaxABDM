/**
 * Open the surgery report in a new window for printing.
 */
export function printSurgeryReport(data) {
  const html = buildSurgeryReportHtml(data);
  const w = window.open('', '_blank', 'width=900,height=700');
  if (!w) return;
  w.document.open();
  w.document.write(html);
  w.document.close();
  setTimeout(() => { w.focus(); w.print(); w.onafterprint = () => w.close(); }, 600);
}

/**
 * Download the surgery report as HTML for saving as PDF.
 */
export function downloadSurgeryReport(data, filename) {
  const html = buildSurgeryReportHtml(data);
  const blob = new Blob([html], { type: 'text/html' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `${filename || 'surgery-report'}.html`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
