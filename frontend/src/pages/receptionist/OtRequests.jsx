import { useEffect, useState, useCallback } from 'react';
import { useNavigate } from 'react-router-dom';
import { MdLocalHospital, MdReceiptLong, MdPayment, MdPrint, MdCheckCircle } from 'react-icons/md';
import api from '../../utils/api';

const STATUS_LABELS = {
  OT_REQUEST_CREATED: 'Request Created',
  PAYMENT_PENDING: 'Payment Pending',
  PAYMENT_COMPLETED: 'Payment Completed',
  APPROVED_FOR_OT: 'Approved for OT',
};
const STATUS_COLORS = {
  OT_REQUEST_CREATED: '#6366f1',
  PAYMENT_PENDING: '#f59e0b',
  PAYMENT_COMPLETED: '#10b981',
  APPROVED_FOR_OT: '#3b82f6',
};

function Badge({ status }) {
  const bg = STATUS_COLORS[status] || '#64748b';
  return (
    <span style={{
      display: 'inline-flex', alignItems: 'center', gap: 4,
      padding: '4px 10px', borderRadius: 999, fontSize: 12, fontWeight: 500,
      background: `${bg}18`, color: bg, border: `1px solid ${bg}30`, whiteSpace: 'nowrap',
    }}>
      {STATUS_LABELS[status] || status}
    </span>
  );
}

function Overlay({ children, onClose }) {
  return (
    <div style={{ position: 'fixed', inset: 0, background: 'rgba(15,23,42,0.45)', display: 'flex', alignItems: 'flex-start', justifyContent: 'center', padding: 16, zIndex: 9999, overflow: 'auto' }}
      onClick={onClose}>
      <div style={{ width: '100%', maxWidth: 820, background: '#fff', borderRadius: 16, border: '1px solid #e2e8f0', boxShadow: '0 30px 70px -45px rgba(0,0,0,0.55)', margin: '24px auto', overflow: 'hidden' }}
        onClick={(e) => e.stopPropagation()}>
        {children}
      </div>
    </div>
  );
}

function OverlayHeader({ title, sub, onClose, extra }) {
  return (
    <div style={{ display: 'flex', alignItems: 'flex-start', justifyContent: 'space-between', gap: 10, padding: '12px 14px', borderBottom: '1px solid #e2e8f0', background: '#f8faff' }}>
      <div>
        <p style={{ margin: 0, fontSize: 14, fontWeight: 600 }}>{title}</p>
        {sub ? <p style={{ margin: '4px 0 0', fontSize: 12, color: '#64748b' }}>{sub}</p> : null}
      </div>
      <div style={{ display: 'flex', gap: 8, alignItems: 'center' }}>
        {extra}
        <button onClick={onClose} style={{ height: 34, padding: '0 12px', borderRadius: 12, border: '1px solid #e2e8f0', background: '#fff', cursor: 'pointer', fontSize: 12, fontWeight: 500, color: '#475569' }}>
          Close
        </button>
      </div>
    </div>
  );
}

function printReceipt(bill) {
  const receiptId = `RCPT-${String(bill.billNumber || '').replace(/\D/g, '').slice(-8)}${Date.now().toString(36).slice(-4)}`;
  const win = window.open('', '_blank');
  if (!win) return;
  const lines = (bill.lineItems || []).map((li) =>
    `<tr><td>${li.description}</td><td style="text-align:center">${li.quantity}</td><td style="text-align:right">₹${li.unitPrice}</td><td style="text-align:right">₹${li.lineTotal}</td></tr>`
  ).join('');
  const payments = (bill.payments || []).map((p) =>
    `<tr><td>${new Date(p.createdAt).toLocaleString('en-IN')}</td><td>${p.mode}</td><td style="text-align:right">₹${p.amount}</td></tr>`
  ).join('');
  win.document.write(`<html><head><title>Receipt ${receiptId}</title>
  <style>body{font-family:sans-serif;padding:20px;color:#1e293b}table{width:100%;border-collapse:collapse}th,td{padding:8px;border:1px solid #e2e8f0;text-align:left}th{background:#f8faff}.right{text-align:right}</style>
  </head><body>
  <h2>VyanX Hospital Management System</h2>
  <p><strong>Receipt:</strong> ${receiptId}</p>
  <p><strong>Bill:</strong> ${bill.billNumber} | <strong>Status:</strong> ${bill.status}</p>
  <h3>Charges</h3>
  <table><thead><tr><th>Description</th><th>Qty</th><th>Rate</th><th>Amount</th></tr></thead><tbody>${lines}</tbody></table>
  <p><strong>Subtotal:</strong> ₹${bill.subtotalAmount} | <strong>Discount:</strong> ₹${bill.discountAmount} | <strong>Tax:</strong> ₹${bill.taxAmount}</p>
  <p><strong>Total:</strong> ₹${bill.totalAmount} | <strong>Paid:</strong> ₹${bill.paidAmount}</p>
  ${payments ? `<h3>Payment History</h3><table><thead><tr><th>Date</th><th>Mode</th><th>Amount</th></tr></thead><tbody>${payments}</tbody></table>` : ''}
  <p style="margin-top:30px;font-size:12px;color:#94a3b8">Generated by VyanX Hospital Management System</p>
  </body></html>`);
  win.document.close();
  win.focus();
  win.print();
}

export default function OtRequests() {
  const navigate = useNavigate();
  const [requests, setRequests] = useState([]);
  const [loading, setLoading] = useState(true);
  const [fetchError, setFetchError] = useState('');
  const [filter, setFilter] = useState('');
  const [searchInput, setSearchInput] = useState('');
  const [searchQuery, setSearchQuery] = useState('');
  const [detailReq, setDetailReq] = useState(null);
  const [preAssessment, setPreAssessment] = useState(null);

  // Payment state
  const [payFormOpen, setPayFormOpen] = useState(false);
  const [payAmount, setPayAmount] = useState(0);
  const [payMode, setPayMode] = useState('Cash');
  const [paySubmitting, setPaySubmitting] = useState(false);
  const [payResult, setPayResult] = useState(null);

  // View bill modal
  const [viewBill, setViewBill] = useState(null);

  const fetchRequests = useCallback(async () => {
    setLoading(true);
    setFetchError('');
    try {
      const params = { limit: 100 };
      if (filter) params.status = filter;
      if (searchQuery.trim()) params.q = searchQuery.trim();
      const res = await api.get('/receptionist/ot', { params });
      setRequests(Array.isArray(res?.data?.items) ? res.data.items : []);
    } catch (err) {
      setRequests([]);
      setFetchError(err?.response?.data?.message || 'Failed to load OT requests');
    } finally {
      setLoading(false);
    }
  }, [filter, searchQuery]);

  useEffect(() => { fetchRequests(); }, [fetchRequests]);

  useEffect(() => {
    if (!detailReq?.id) { setPreAssessment(null); return; }
    let alive = true;
    api.get('/assessment/ot-request/' + detailReq.id)
      .then((res) => { if (alive) setPreAssessment(res?.data?.assessment || null); })
      .catch(() => { if (alive) setPreAssessment(null); });
    return () => { alive = false; };
  }, [detailReq?.id]);

  useEffect(() => {
    const onFocus = () => fetchRequests();
    window.addEventListener('focus', onFocus);
    return () => window.removeEventListener('focus', onFocus);
  }, [fetchRequests]);

  useEffect(() => {
    const timer = setTimeout(() => setSearchQuery(searchInput.trim()), 300);
    return () => clearTimeout(timer);
  }, [searchInput]);

  const handlePay = async () => {
    if (!payAmount || payAmount <= 0) return;
    setPaySubmitting(true);
    try {
      const res = await api.post(`/receptionist/ot/${detailReq.id}/pay`, {
        amount: Number(payAmount), mode: payMode,
      });
      setPayResult(res.data);
      setPayFormOpen(false);
      await fetchRequests();
      const detail = await api.get(`/receptionist/ot/${detailReq.id}`);
      setDetailReq(detail.data.otRequest);
    } catch (err) {
      alert(err?.response?.data?.message || 'Payment failed');
    } finally {
      setPaySubmitting(false);
    }
  };

  const handleApprove = async () => {
    if (!window.confirm('Approve this patient for OT surgery?')) return;
    try {
      await api.post(`/receptionist/ot/${detailReq.id}/approve`);
      await fetchRequests();
      const detail = await api.get(`/receptionist/ot/${detailReq.id}`);
      setDetailReq(detail.data.otRequest);
    } catch (err) {
      alert(err?.response?.data?.message || 'Approval failed');
    }
  };

  const viewBillDetails = async () => {
    try {
      const res = await api.get(`/receptionist/ot/${detailReq.id}/bill`);
      setViewBill(res.data.bill);
    } catch (err) {
      alert(err?.response?.data?.message || 'Failed to load bill');
    }
  };

  return (
    <div style={{ padding: '18px 18px 26px', color: '#0f172a' }}>
      <div style={{ display: 'flex', flexDirection: 'column', gap: 12, marginBottom: 16 }}>
        <div style={{ display: 'flex', alignItems: 'center', justifyContent: 'space-between', flexWrap: 'wrap', gap: 12 }}>
      
          <select value={filter} onChange={(e) => setFilter(e.target.value)}
            style={{ height: 38, borderRadius: 12, border: '1px solid #cbd5e1', padding: '0 10px', fontSize: 13, background: '#fff', color: '#0f172a' }}>
            <option value="">All Statuses</option>
            <option value="OT_REQUEST_CREATED">Request Created</option>
            <option value="PAYMENT_PENDING">Payment Pending</option>
            <option value="PAYMENT_COMPLETED">Payment Completed</option>
            <option value="APPROVED_FOR_OT">Approved for OT</option>
          </select>
          <button type="button" onClick={fetchRequests}
            style={{ height: 38, padding: '0 14px', borderRadius: 12, border: '1px solid #cbd5e1', background: '#fff', cursor: 'pointer', fontSize: 12, fontWeight: 500 }}>
            Refresh
          </button>
        </div>
        <div style={{ display: 'flex', gap: 8, alignItems: 'center' }}>
          <input
            type="text"
            value={searchInput}
            onChange={(e) => setSearchInput(e.target.value)}
            placeholder="Search by Patient Name, UHID, Request #, Surgery..."
            style={{ flex: 1, height: 40, borderRadius: 12, border: '1px solid #cbd5e1', padding: '0 12px', fontSize: 13 }}
          />
          {searchInput ? (
            <button type="button" onClick={() => { setSearchInput(''); setSearchQuery(''); }}
              style={{ height: 40, padding: '0 14px', borderRadius: 12, border: '1px solid #e2e8f0', background: '#fff', cursor: 'pointer', fontSize: 12, fontWeight: 500 }}>
              Clear
            </button>
          ) : null}
        </div>
      </div>

      {fetchError ? (
        <div style={{ marginBottom: 12, padding: '10px 14px', borderRadius: 10, background: '#fef2f2', color: '#dc2626', border: '1px solid #fecaca', fontSize: 13 }}>
          {fetchError}
        </div>
      ) : null}

      {loading ? (
        <div style={{ textAlign: 'center', padding: 40, color: '#64748b' }}>Loading...</div>
      ) : requests.length === 0 ? (
        <div style={{ background: '#fff', border: '1px dashed #94a3b8', borderRadius: 16, padding: '40px 20px', textAlign: 'center' }}>
          <MdLocalHospital size={40} color="#94a3b8" style={{ marginBottom: 8 }} />
          <p style={{ margin: 0, fontWeight: 600, color: '#475569' }}>No OT requests</p>
          <p style={{ margin: '4px 0 0', fontSize: 13, color: '#94a3b8' }}>
            Nurse must complete pre-assessment first. Then refresh this page.
          </p>
        </div>
      ) : (
        <div style={{ display: 'flex', flexDirection: 'column', gap: 12 }}>
          {requests.map((req) => (
            <div key={req.id}
              style={{ background: '#fff', border: '1px solid #e2e8f0', borderRadius: 14, padding: 14, boxShadow: '0 2px 8px rgba(0,0,0,0.04)', cursor: 'pointer' }}
              onClick={() => navigate('/dashboard/reception/ot-requests/generate-bill', { state: { preselectedId: req.id } })}>
              <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'flex-start', marginBottom: 8 }}>
                <div>
                  <p style={{ margin: 0, fontSize: 14, fontWeight: 600 }}>
                    {req.patient?.name || 'Unknown'} <span style={{ fontWeight: 400, color: '#64748b', fontFamily: 'monospace' }}>#{req.uhid}</span>
                  </p>
                  <p style={{ margin: '2px 0 0', fontSize: 12, color: '#64748b' }}>
                    {req.requestNumber} &middot; {req.nurse?.name || '—'} &middot; {req.doctor?.user?.name || '—'}
                  </p>
                </div>
                <Badge status={req.status} />
              </div>
              <div style={{ fontSize: 12, color: '#475569' }}>
                <strong>Diagnosis:</strong> {req.diagnosis} &middot; <strong>Surgery:</strong> {req.surgeryRecommendation}
                &middot; <strong>Expected:</strong> {new Date(req.expectedSurgeryDate).toLocaleDateString('en-IN')}
                &middot; <strong>Priority:</strong> {req.priority}
              </div>
            </div>
          ))}
        </div>
      )}

      {/* ─── Detail Modal ─── */}
      {detailReq && (
        <Overlay onClose={() => { setDetailReq(null); setPayResult(null); setViewBill(null); setPayFormOpen(false); }}>
          <OverlayHeader
            title="OT Request Details"
            sub={`${detailReq.requestNumber} · ${detailReq.patient?.name} (#${detailReq.uhid})`}
            onClose={() => { setDetailReq(null); setPayResult(null); setViewBill(null); setPayFormOpen(false); }}
            extra={<Badge status={detailReq.status} />}
          />
          <div style={{ padding: 14 }}>
            {/* Patient & Medical Info */}
            <div style={{ display: 'grid', gridTemplateColumns: '1fr 1fr', gap: 12 }}>
              <div style={{ border: '1px solid #e2e8f0', borderRadius: 14, padding: 12 }}>
                <p style={{ margin: 0, fontSize: 13, fontWeight: 600 }}>Patient Info</p>
                <div style={{ marginTop: 10, display: 'flex', flexDirection: 'column', gap: 6, fontSize: 13 }}>
                  <div><strong>Name:</strong> {detailReq.patient?.name}</div>
                  <div><strong>UHID:</strong> {detailReq.uhid}</div>
                  <div><strong>IPD:</strong> {detailReq.admission?.ipdNumber || '—'}</div>
                  <div><strong>Ward/Bed:</strong> {detailReq.admission?.ward?.name || '—'} / {detailReq.admission?.bedNumber || '—'}</div>
                </div>
              </div>
              <div style={{ border: '1px solid #e2e8f0', borderRadius: 14, padding: 12 }}>
                <p style={{ margin: 0, fontSize: 13, fontWeight: 600 }}>Medical Info</p>
                <div style={{ marginTop: 10, display: 'flex', flexDirection: 'column', gap: 6, fontSize: 13 }}>
                  <div><strong>Diagnosis:</strong> {detailReq.diagnosis}</div>
                  <div><strong>Surgery:</strong> {detailReq.surgeryRecommendation}</div>
                  <div><strong>Priority:</strong> {detailReq.priority}</div>
                  <div><strong>Expected:</strong> {new Date(detailReq.expectedSurgeryDate).toLocaleDateString('en-IN')}</div>
                  <div><strong>Doctor:</strong> {detailReq.doctor?.user?.name || '—'}</div>
                  <div><strong>Nurse:</strong> {detailReq.nurse?.name || '—'}</div>
                  {detailReq.notes ? <div><strong>Notes:</strong> {detailReq.notes}</div> : null}
                </div>
              </div>
            </div>

            {preAssessment ? (
              <div style={{ marginTop: 12, border: '1px solid #e2e8f0', borderRadius: 14, padding: 12 }}>
                <p style={{ margin: 0, fontSize: 13, fontWeight: 600, marginBottom: 8 }}>
                  <MdCheckCircle style={{ color: '#15803d', verticalAlign: 'middle', marginRight: 4 }} />
                  Pre-Operative Assessment <span style={{ fontWeight: 400, color: '#15803d', fontSize: 11 }}>(completed)</span>
                </p>
                <div style={{ display: 'grid', gridTemplateColumns: '1fr 1fr 1fr', gap: 6, fontSize: 12 }}>
                  <div><strong>BP:</strong> {preAssessment.bpSystolic || '—'}/{preAssessment.bpDiastolic || '—'}</div>
                  <div><strong>Pulse:</strong> {preAssessment.pulse ?? '—'}</div>
                  <div><strong>Temp:</strong> {preAssessment.temperature ?? '—'}</div>
                  <div><strong>SpO₂:</strong> {preAssessment.spo2 ?? '—'}</div>
                  <div><strong>RR:</strong> {preAssessment.respiratoryRate ?? '—'}</div>
                  <div><strong>BMI:</strong> {preAssessment.bmi ?? '—'}</div>
                  <div><strong>Height:</strong> {preAssessment.heightCm ?? '—'}</div>
                  <div><strong>Weight:</strong> {preAssessment.weightKg ?? '—'}</div>
                  <div><strong>Assessed By:</strong> {preAssessment.assessedBy?.name || '—'}</div>
                </div>
                <div style={{ marginTop: 6, display: 'flex', flexWrap: 'wrap', gap: '2px 12px', fontSize: 12, color: '#374151' }}>
                  {preAssessment.diabetes && <span><MdCheckCircle style={{ color: '#15803d', verticalAlign: 'middle', fontSize: 13 }} /> Diabetes</span>}
                  {preAssessment.hypertension && <span><MdCheckCircle style={{ color: '#15803d', verticalAlign: 'middle', fontSize: 13 }} /> Hypertension</span>}
                  {preAssessment.asthma && <span><MdCheckCircle style={{ color: '#15803d', verticalAlign: 'middle', fontSize: 13 }} /> Asthma</span>}
                  {preAssessment.heartDisease && <span><MdCheckCircle style={{ color: '#15803d', verticalAlign: 'middle', fontSize: 13 }} /> Heart Disease</span>}
                  {preAssessment.kidneyDisease && <span><MdCheckCircle style={{ color: '#15803d', verticalAlign: 'middle', fontSize: 13 }} /> Kidney Disease</span>}
                  {preAssessment.consentObtained && <span><MdCheckCircle style={{ color: '#15803d', verticalAlign: 'middle', fontSize: 13 }} /> Consent</span>}
                  {preAssessment.labReportsAvailable && <span><MdCheckCircle style={{ color: '#15803d', verticalAlign: 'middle', fontSize: 13 }} /> Lab Reports</span>}
                  {preAssessment.fastingCompleted && <span><MdCheckCircle style={{ color: '#15803d', verticalAlign: 'middle', fontSize: 13 }} /> Fasting</span>}
                  {preAssessment.bloodAvailable && <span><MdCheckCircle style={{ color: '#15803d', verticalAlign: 'middle', fontSize: 13 }} /> Blood</span>}
                  {preAssessment.surgicalSiteVerified && <span><MdCheckCircle style={{ color: '#15803d', verticalAlign: 'middle', fontSize: 13 }} /> Site Verified</span>}
                  {preAssessment.patientIdentityVerified && <span><MdCheckCircle style={{ color: '#15803d', verticalAlign: 'middle', fontSize: 13 }} /> Identity</span>}
                </div>
                {preAssessment.knownAllergies && <div style={{ marginTop: 4, fontSize: 12 }}><strong>Allergies:</strong> {preAssessment.knownAllergies}</div>}
                {preAssessment.currentMedications && <div style={{ marginTop: 2, fontSize: 12 }}><strong>Medications:</strong> {preAssessment.currentMedications}</div>}
                {preAssessment.previousSurgeries && <div style={{ marginTop: 2, fontSize: 12 }}><strong>Surgeries:</strong> {preAssessment.previousSurgeries}</div>}
                {preAssessment.nurseNotes && <div style={{ marginTop: 2, fontSize: 12 }}><strong>Nurse Notes:</strong> {preAssessment.nurseNotes}</div>}
              </div>
            ) : detailReq.status === 'OT_REQUEST_CREATED' || detailReq.status === 'PAYMENT_PENDING' ? (
              <div style={{ marginTop: 12, border: '1px solid #fef3c7', borderRadius: 14, padding: 12, background: '#fffbeb', fontSize: 12, color: '#92400e' }}>
                Pre-operative assessment not yet completed by nurse.
              </div>
            ) : null}

            {/* Workflow Progress */}
            <div style={{ marginTop: 12, border: '1px solid #e2e8f0', borderRadius: 14, padding: 12 }}>
              <p style={{ margin: 0, fontSize: 13, fontWeight: 600, marginBottom: 8 }}>Workflow</p>
              <div style={{ display: 'flex', gap: 0, alignItems: 'center' }}>
                {[
                  { label: 'OT Request', done: true },
                  { label: 'Bill Generated', done: Boolean(detailReq.bill) },
                  { label: 'Payment Done', done: detailReq.status === 'PAYMENT_COMPLETED' || detailReq.status === 'APPROVED_FOR_OT' },
                  { label: 'Approved', done: detailReq.status === 'APPROVED_FOR_OT' },
                ].map((step, i) => (
                  <div key={step.label} style={{ flex: 1, textAlign: 'center', position: 'relative' }}>
                    <div style={{ width: 28, height: 28, borderRadius: '50%', margin: '0 auto', display: 'flex', alignItems: 'center', justifyContent: 'center',
                      background: step.done ? '#15803d' : '#e2e8f0', color: step.done ? '#fff' : '#94a3b8', fontSize: 13, fontWeight: 700 }}>
                      {step.done ? '✓' : i + 1}
                    </div>
                    <p style={{ margin: '4px 0 0', fontSize: 10, color: step.done ? '#15803d' : '#94a3b8', fontWeight: step.done ? 600 : 400 }}>{step.label}</p>
                  </div>
                ))}
              </div>
            </div>

            {/* Billing Section */}
            {detailReq.bill && (
              <div style={{ marginTop: 12, border: '1px solid #e2e8f0', borderRadius: 14, padding: 12 }}>
                <p style={{ margin: 0, fontSize: 13, fontWeight: 600 }}>Billing Info</p>
                <div style={{ marginTop: 10, display: 'flex', flexDirection: 'column', gap: 6, fontSize: 13 }}>
                  <div><strong>Bill Number:</strong> {detailReq.bill.billNumber}</div>
                  <div><strong>Total:</strong> ₹{detailReq.bill.totalAmount} | <strong>Paid:</strong> ₹{detailReq.bill.paidAmount} | <strong>Status:</strong> {detailReq.bill.status}</div>
                  <div style={{ display: 'flex', gap: 8, marginTop: 4 }}>
                    <button onClick={viewBillDetails} style={{ height: 32, padding: '0 12px', borderRadius: 8, border: '1px solid #3b82f6', background: '#eff6ff', color: '#1d4ed8', cursor: 'pointer', fontSize: 12, fontWeight: 600, display: 'flex', alignItems: 'center', gap: 4 }}>
                      <MdReceiptLong /> View OT Bill
                    </button>
                    {detailReq.bill.status === 'DRAFT' && (
                      <span style={{ fontSize: 11, color: '#f59e0b', display: 'flex', alignItems: 'center', gap: 4 }}>
                        <MdBlock /> Draft - Generate final bill to proceed
                      </span>
                    )}
                  </div>
                </div>
              </div>
            )}

            {/* Action Buttons */}
            <div style={{ marginTop: 12, display: 'flex', gap: 8, justifyContent: 'flex-end', flexWrap: 'wrap', alignItems: 'center' }}>
              {detailReq.status === 'OT_REQUEST_CREATED' && !detailReq.bill && (
                <span style={{ fontSize: 12, color: '#3b82f6', padding: '6px 12px', borderRadius: 8, background: '#eff6ff', border: '1px solid #bfdbfe' }}>
                  Go to <strong>Generate OT Bill</strong> page to create bill
                </span>
              )}
              {(detailReq.status === 'PAYMENT_PENDING' || (detailReq.status === 'OT_REQUEST_CREATED' && detailReq.bill && detailReq.bill.status === 'PENDING')) && (
                <button onClick={() => {
                  const pending = (detailReq.bill?.totalAmount || 0) - (detailReq.bill?.paidAmount || 0);
                  setPayAmount(pending > 0 ? pending : 0);
                  setPayMode('Cash');
                  setPayFormOpen(true);
                }}
                  style={{ height: 38, padding: '0 16px', borderRadius: 12, border: 'none', background: '#f59e0b', color: '#fff', cursor: 'pointer', fontSize: 13, fontWeight: 600, display: 'flex', alignItems: 'center', gap: 4 }}>
                  <MdPayment /> Proceed To Payment
                </button>
              )}

              {detailReq.status === 'PAYMENT_COMPLETED' && (
                <button onClick={handleApprove}
                  style={{ height: 38, padding: '0 16px', borderRadius: 12, border: 'none', background: '#15803d', color: '#fff', cursor: 'pointer', fontSize: 13, fontWeight: 600, display: 'flex', alignItems: 'center', gap: 4 }}>
                  <MdCheckCircle /> Approve For OT
                </button>
              )}

              {detailReq.status === 'APPROVED_FOR_OT' && (
                <div style={{ display: 'flex', alignItems: 'center', gap: 6, padding: '6px 14px', borderRadius: 12, background: '#f0fdf4', border: '1px solid #bbf7d0', color: '#15803d', fontSize: 13, fontWeight: 600 }}>
                  <MdCheckCircle /> Approved For OT
                </div>
              )}
            </div>
          </div>
        </Overlay>
      )}

      {/* ─── Payment Form ─── */}
      {payFormOpen && detailReq && (
        <Overlay onClose={() => setPayFormOpen(false)}>
          <OverlayHeader title="Proceed To Payment" sub={`${detailReq.patient?.name} (#${detailReq.uhid})`} onClose={() => setPayFormOpen(false)} />
          <div style={{ padding: 14 }}>
            <div style={{ border: '1px solid #e2e8f0', borderRadius: 14, padding: 12, marginBottom: 12 }}>
              <div style={{ fontSize: 13, marginBottom: 6 }}><strong>Bill:</strong> {detailReq.bill?.billNumber || '—'}</div>
              <div style={{ fontSize: 13 }}><strong>Total:</strong> ₹{detailReq.bill?.totalAmount || 0} | <strong>Paid:</strong> ₹{detailReq.bill?.paidAmount || 0} | <strong>Pending:</strong> ₹{(detailReq.bill?.totalAmount || 0) - (detailReq.bill?.paidAmount || 0)}</div>
            </div>
            <div style={{ display: 'grid', gridTemplateColumns: '1fr 1fr', gap: 12, marginBottom: 12 }}>
              <div>
                <label style={{ fontSize: 11, fontWeight: 600, color: '#64748b' }}>Amount (₹)</label>
                <input type="number" min="1" value={payAmount} onChange={(e) => setPayAmount(e.target.value)}
                  style={{ height: 38, borderRadius: 8, border: '1px solid #cbd5e1', padding: '0 8px', fontSize: 13, width: '100%' }} />
              </div>
              <div>
                <label style={{ fontSize: 11, fontWeight: 600, color: '#64748b' }}>Payment Mode</label>
                <select value={payMode} onChange={(e) => setPayMode(e.target.value)}
                  style={{ height: 38, borderRadius: 8, border: '1px solid #cbd5e1', padding: '0 8px', fontSize: 13, width: '100%' }}>
                  <option value="Cash">Cash</option>
                  <option value="UPI">UPI</option>
                  <option value="Card">Card</option>
                  <option value="Insurance">Insurance</option>
                </select>
              </div>
            </div>
            <div style={{ display: 'flex', gap: 8, justifyContent: 'flex-end' }}>
              <button onClick={() => setPayFormOpen(false)}
                style={{ height: 36, padding: '0 14px', borderRadius: 10, border: '1px solid #e2e8f0', background: '#fff', cursor: 'pointer', fontSize: 12, fontWeight: 500 }}>
                Cancel
              </button>
              <button onClick={handlePay} disabled={paySubmitting || !payAmount || payAmount <= 0}
                style={{ height: 36, padding: '0 14px', borderRadius: 10, border: 'none', background: '#059669', color: '#fff', cursor: 'pointer', fontSize: 13, fontWeight: 600 }}>
                {paySubmitting ? 'Processing...' : `Pay ₹${payAmount}`}
              </button>
            </div>
          </div>
        </Overlay>
      )}

      {/* ─── Payment Success ─── */}
      {payResult && detailReq && (
        <Overlay onClose={() => { setPayResult(null); fetchRequests(); }}>
          <OverlayHeader title="Payment Successful" sub={`Receipt: ${payResult.receiptId}`}
            onClose={() => { setPayResult(null); fetchRequests(); }} />
          <div style={{ padding: 14 }}>
            <div style={{ background: '#f0fdf4', border: '1px solid #bbf7d0', borderRadius: 14, padding: 16, textAlign: 'center', marginBottom: 12 }}>
              <p style={{ margin: 0, fontSize: 15, fontWeight: 700, color: '#15803d' }}>Payment Recorded</p>
              <p style={{ margin: '4px 0 0', fontSize: 13, color: '#166534' }}>Bill: {payResult.bill.billNumber} | Paid: ₹{payResult.bill.paidAmount}</p>
              {payResult.fullyPaid && (
                <p style={{ margin: '4px 0 0', fontSize: 13, color: '#15803d', fontWeight: 600 }}>Bill fully paid. You can now approve for OT.</p>
              )}
            </div>
            <div style={{ display: 'flex', gap: 8, justifyContent: 'flex-end' }}>
              <button onClick={() => printReceipt(payResult.bill)}
                style={{ height: 36, padding: '0 14px', borderRadius: 10, border: '1px solid #e2e8f0', background: '#fff', cursor: 'pointer', fontSize: 12, fontWeight: 500, display: 'flex', alignItems: 'center', gap: 4 }}>
                <MdPrint /> Print Receipt
              </button>
              <button onClick={async () => {
                setPayResult(null);
                await fetchRequests();
                const detail = await api.get(`/receptionist/ot/${detailReq.id}`);
                setDetailReq(detail.data.otRequest);
              }}
                style={{ height: 36, padding: '0 14px', borderRadius: 10, border: 'none', background: '#3b82f6', color: '#fff', cursor: 'pointer', fontSize: 13, fontWeight: 600 }}>
                Done
              </button>
            </div>
          </div>
        </Overlay>
      )}

      {/* ─── View Bill Modal ─── */}
      {viewBill && (
        <Overlay onClose={() => setViewBill(null)}>
          <OverlayHeader title="OT Bill" sub={`Bill #${viewBill.billNumber}`} onClose={() => setViewBill(null)}
            extra={<span style={{ fontSize: 12, padding: '4px 10px', borderRadius: 999, fontWeight: 500,
              background: viewBill.status === 'PAID' ? 'rgba(21,128,61,0.10)' : viewBill.status === 'DRAFT' ? 'rgba(245,158,11,0.10)' : 'rgba(99,102,241,0.10)',
              color: viewBill.status === 'PAID' ? '#15803d' : viewBill.status === 'DRAFT' ? '#92400e' : '#6366f1',
              border: `1px solid ${viewBill.status === 'PAID' ? 'rgba(21,128,61,0.22)' : viewBill.status === 'DRAFT' ? 'rgba(245,158,11,0.22)' : 'rgba(99,102,241,0.22)'}` }}>
              {viewBill.status}
            </span>} />
          <div style={{ padding: 14 }}>
            {viewBill.lineItems?.length > 0 && (
              <div style={{ border: '1px solid #e2e8f0', borderRadius: 14, padding: 12, marginBottom: 12 }}>
                <p style={{ margin: 0, fontSize: 12, fontWeight: 600, marginBottom: 8 }}>Charges Breakdown</p>
                {viewBill.lineItems.map((li) => (
                  <div key={li.id} style={{ display: 'flex', justifyContent: 'space-between', fontSize: 13, padding: '6px 0', borderBottom: '1px solid #f1f5f9' }}>
                    <span>{li.description}</span><span style={{ fontWeight: 500 }}>₹{li.lineTotal}</span>
                  </div>
                ))}
                <div style={{ display: 'flex', justifyContent: 'space-between', fontSize: 12, padding: '6px 0', color: '#64748b' }}>
                  <span>Subtotal</span><span>₹{viewBill.subtotalAmount}</span>
                </div>
                <div style={{ display: 'flex', justifyContent: 'space-between', fontSize: 12, padding: '4px 0', color: '#64748b' }}>
                  <span>Discount</span><span>-₹{viewBill.discountAmount}</span>
                </div>
                <div style={{ display: 'flex', justifyContent: 'space-between', fontSize: 12, padding: '4px 0', color: '#64748b' }}>
                  <span>Tax</span><span>+₹{viewBill.taxAmount}</span>
                </div>
                <div style={{ display: 'flex', justifyContent: 'space-between', fontSize: 15, padding: '8px 0 0', borderTop: '2px solid #e2e8f0', marginTop: 4, fontWeight: 700 }}>
                  <span>Total</span><span>₹{viewBill.totalAmount}</span>
                </div>
              </div>
            )}

            {viewBill.payments?.length > 0 && (
              <div style={{ border: '1px solid #e2e8f0', borderRadius: 14, padding: 12, marginBottom: 12 }}>
                <p style={{ margin: 0, fontSize: 12, fontWeight: 600, marginBottom: 8 }}>Payment History</p>
                {viewBill.payments.map((p) => (
                  <div key={p.id} style={{ display: 'flex', justifyContent: 'space-between', fontSize: 13, padding: '4px 0', borderBottom: '1px solid #f1f5f9' }}>
                    <span>{p.mode} - {new Date(p.createdAt).toLocaleString('en-IN')}</span><span style={{ fontWeight: 500 }}>₹{p.amount}</span>
                  </div>
                ))}
                <div style={{ display: 'flex', justifyContent: 'space-between', fontSize: 14, padding: '8px 0 0', borderTop: '2px solid #e2e8f0', marginTop: 4, fontWeight: 700, color: '#15803d' }}>
                  <span>Total Paid</span><span>₹{viewBill.paidAmount}</span>
                </div>
              </div>
            )}

            <div style={{ display: 'flex', gap: 8, justifyContent: 'flex-end' }}>
              <button onClick={() => printReceipt(viewBill)}
                style={{ height: 36, padding: '0 14px', borderRadius: 10, border: '1px solid #e2e8f0', background: '#fff', cursor: 'pointer', fontSize: 12, fontWeight: 500, display: 'flex', alignItems: 'center', gap: 4 }}>
                <MdPrint /> Print Receipt
              </button>
              <button onClick={() => setViewBill(null)}
                style={{ height: 36, padding: '0 14px', borderRadius: 10, border: 'none', background: '#3b82f6', color: '#fff', cursor: 'pointer', fontSize: 13, fontWeight: 600 }}>
                Close
              </button>
            </div>
          </div>
        </Overlay>
      )}
    </div>
  );
}
